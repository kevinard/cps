#!/usr/bin/env python3
"""Generate section 1 man pages from the help of a built CPS binary."""

import argparse
import os
from pathlib import Path
import re
import subprocess


def read_help(binary, command):
    output = subprocess.check_output(
        [binary, *command, "--help"],
        text=True,
        env={**os.environ, "LC_ALL": "C", "NO_COLOR": "1"},
    ).rstrip()
    description, body = output.split("\n\nUsage: ", 1)
    synopsis, *blocks = re.split(r"\n\n(?=[A-Z][^\n]*:\n)", body)
    sections = {}
    for block in blocks:
        heading, rows = block.split(":\n", 1)
        entries = []
        for line in rows.splitlines():
            if not line.strip():
                continue
            if not line.startswith(" "):
                # Unindented text after a section is closing prose, such as after_help notes.
                sections.setdefault(NOTES, []).append((line, ""))
                continue
            if line.startswith("          "):
                term, detail = entries[-1]
                entries[-1] = term, f"{detail} {line.strip()}".strip()
                continue
            term, _, detail = re.sub(r" {2,}", "\t", line.strip(), count=1).partition("\t")
            entries.append((term, detail))
        sections[heading] = entries
    return description, synopsis, sections


NOTES = "Notes"
NOT_COMMANDS = {"Arguments", "Options", "Examples", NOTES}


def command_groups(sections):
    """The help sections that list subcommands: Commands, or the top level's task groups."""
    return {
        heading: [(name, summary) for name, summary in entries if name != "help"]
        for heading, entries in sections.items()
        if heading not in NOT_COMMANDS
        and entries
        and all(not name.startswith("-") and " " not in name for name, _ in entries)
    }


def command_names(sections):
    return [name for entries in command_groups(sections).values() for name, _ in entries]


def roff(value):
    """Escape text from help so it renders literally in a man macro or paragraph."""
    return "\\&" + value.replace("\\", r"\e").replace("-", r"\-").replace('"', r"\(dq")


def definition_list(entries):
    lines = []
    for term, detail in entries:
        if detail:
            lines += [".TP", f".B {roff(term)}", roff(detail)]
        else:
            lines += [".PP", f".B {roff(term)}"]
    return lines


def page_header(name, summary, synopsis):
    return [
        '.\\" Generated by docs/reference/generate-man.py from cps --help.',
        f'.TH "{name.upper()}" 1 "" "CPS" "User Commands"',
        ".SH NAME",
        f"{roff(name)} \\- {roff(summary)}",
        ".SH SYNOPSIS",
        ".HP 4",
        f".B {roff(synopsis)}",
    ]


def format_help(description, synopsis, sections, nested=False):
    lines = []
    if nested:
        lines += [roff(description.replace("\n", " ")), ".PP", f".B {roff(synopsis)}"]
    elif "\n" in description or ". " in description:
        lines += [".SH DESCRIPTION", roff(description.replace("\n", " "))]
    for heading, entries in sections.items():
        if heading == NOTES:
            lines += [".PP", roff(" ".join(text for text, _ in entries))]
            continue
        if nested:
            lines += [".PP", f".B {heading}"]
        else:
            lines.append(f".SH {heading.upper()}")
        lines += definition_list(entries)
    return lines


def command_page(binary, command):
    description, synopsis, sections = read_help(binary, command)
    name = "cps-" + "-".join(command)
    summary = description.splitlines()[0].partition(". ")[0].rstrip(".")
    lines = page_header(name, summary, synopsis)
    lines += format_help(description, synopsis, sections)
    if command_names(sections):
        lines.append(".SH SUBCOMMAND REFERENCE")
        lines += subcommand_reference(binary, command, sections)
    lines += [".SH SEE ALSO", ".BR cps (1)"]
    return "\n".join(lines) + "\n"


def subcommand_reference(binary, command, sections):
    """Document every subcommand, including nested groups such as cps repo trust."""
    lines = []
    for child in command_names(sections):
        child_command = (*command, child)
        help_text = read_help(binary, child_command)
        lines.append(f'.SS "{roff("cps " + " ".join(child_command))}"')
        lines += format_help(*help_text, nested=True)
        if command_names(help_text[2]):
            lines += subcommand_reference(binary, child_command, help_text[2])
    return lines


def manual(binary):
    _, synopsis, sections = read_help(binary, ())
    names = command_names(sections)
    lines = page_header("cps", "Canopa Package System", synopsis)
    lines += [
        ".SH DESCRIPTION",
        "CPS manages Linux images using signed package catalogs.",
        "The commands that change packages act on the running system,",
        "a registered CPS Btrfs root described by",
        ".IR /etc/cps/image.kdl .",
        "With",
        f".B {roff('--root')}",
        "they act on an inactive image instead: they plan the change,",
        "fetch its payloads, and apply it.",
        "With",
        f".B {roff('--dry-run --save-plan')}",
        "they save the plan for",
        ".BR cps-fetch (1)",
        "and",
        ".BR cps-apply (1).",
        ".PP",
        "A package selector can be a name, a name with an exact version,",
        "or a publisher-qualified name such as",
        f".BR {roff('cps://canopa/apps/editor@1.0.0-0')} .",
        "Supported selectors depend on the command.",
        ".SH COMMANDS",
    ]
    for heading, entries in command_groups(sections).items():
        lines.append(f'.SS "{roff(heading)}"')
        lines += definition_list([(f"cps-{name}(1)", summary) for name, summary in entries])
    lines += definition_list(
        [("cps help [COMMAND ...]", "Show help for CPS or a specific subcommand.")]
    )
    lines += [".SH OPTIONS", *definition_list(sections["Options"])]
    lines += [
        ".SH FILES",
        ".TP",
        ".I /etc/cps/image.kdl",
        "Default configuration for system commands.",
        ".TP",
        ".I /usr/lib/sysimage/cps/",
        "Package database, transaction staging, prepared kernel files, and vendor configuration "
        "proposals within an image. Packages never ship /var, which tmpfiles.d populates at boot.",
        ".SH EXAMPLES",
        ".EX",
        roff("cps search editor"),
        roff("sudo cps upgrade --dry-run"),
        roff("cps install --root image --yes apps/editor"),
        roff("cps upgrade --root image --dry-run --save-plan upgrade.json"),
        roff("cps fetch --root image upgrade.json"),
        roff("cps apply --root image upgrade.json"),
        ".EE",
        ".SH SEE ALSO",
        ".BR cps-install (1),",
        ".BR cps-apply (1),",
        ".BR cps-repo (1),",
        ".BR cps-boot (1)",
    ]
    return {"cps.1": "\n".join(lines) + "\n"} | {
        f"cps-{name}.1": command_page(binary, (name,)) for name in names
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--cps", type=Path, required=True, help="CPS executable to query")
    parser.add_argument("--output", type=Path, default=Path(__file__).parent / "man")
    parser.add_argument("--check", action="store_true", help="Check existing pages for drift")
    args = parser.parse_args()

    pages = manual(args.cps.resolve())
    stale = {path.name for path in args.output.glob("cps-*.1")} - pages.keys()
    if args.check:
        for name, expected in pages.items():
            path = args.output / name
            if not path.is_file() or path.read_text(encoding="utf-8") != expected:
                stale.add(name)
        if stale:
            parser.exit(1, "Regenerate CPS man pages: " + ", ".join(sorted(stale)) + "\n")
        return

    args.output.mkdir(parents=True, exist_ok=True)
    for name in stale:
        (args.output / name).unlink()
    for name, content in pages.items():
        (args.output / name).write_text(content, encoding="utf-8")


if __name__ == "__main__":
    main()
